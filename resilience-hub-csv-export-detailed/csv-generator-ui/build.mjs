// Builds the RAP pre-check report page and embeds it in csv-generator-nextgen.py:
//   npm ci && npm run build      (or: node build.mjs <path to csv-generator-nextgen.py>)
//
// The page is one self-contained HTML file: React, the Cloudscape components and the Open Sans font are
// inlined, and its Content-Security-Policy allows no network request at all. The script replaces
// PLACEHOLDER with the report data.
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';

const PLACEHOLDER = '__RAP_REPORT_DATA__';
const BEGIN = '# BEGIN REPORT PAGE';
const END = '# END REPORT PAGE';

const result = await build({
  entryPoints: ['src/main.jsx'],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2020',
  jsx: 'automatic',
  charset: 'utf8',
  legalComments: 'none', // the licenses are added once, at the end of the page
  define: { 'process.env.NODE_ENV': '"production"' },
  outdir: 'dist',
  write: false,
  metafile: true,
});
const js = result.outputFiles.find(file => file.path.endsWith('.js')).text;
const css = result.outputFiles.find(file => file.path.endsWith('.css')).text;

// Open Sans regular and bold, the two weights Cloudscape uses
const fonts = readFileSync('node_modules/@cloudscape-design/global-styles/fonts.css', 'utf8')
  .match(/@font-face\s*{[^}]*}/g)
  .filter(block => /font-style:\s*normal/.test(block) && /font-weight:\s*(400|700);/.test(block));
if (fonts.length !== 2) {
  throw new Error(`expected Open Sans 400 and 700 in global-styles, found ${fonts.length}`);
}

// Every bundled package with its license texts, for the notice at the end of the page
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  const match = input.match(/^(.*node_modules\/((?:@[^/]+\/)?[^/]+))\//);
  if (match && !packages.has(match[2])) {
    const meta = JSON.parse(readFileSync(`${match[1]}/package.json`, 'utf8'));
    const texts = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'NOTICE', 'THIRD-PARTY-LICENSES.txt', 'THIRD-PARTY-LICENSES']
      .filter(name => existsSync(`${match[1]}/${name}`))
      .map(name => readFileSync(`${match[1]}/${name}`, 'utf8').trim());
    packages.set(match[2], { title: `${meta.name} ${meta.version} (${meta.license})`, texts });
  }
}
const titles = [...packages.values()].map(p => p.title).sort();
const licenses = [...new Set([...packages.values()].flatMap(p => p.texts))].join('\n\n------\n\n');

for (const [name, text] of [['script', js], ['style', css], ['notice', licenses]]) {
  if (/<\/(script|style)/i.test(text) || text.includes('-->') || text.includes('--!>') || text.includes(PLACEHOLDER)) {
    throw new Error(`the ${name} can't be inlined as is`);
  }
}
const csp = [
  "default-src 'none'",
  `script-src 'sha256-${createHash('sha256').update(js, 'utf8').digest('base64')}'`,
  "style-src 'unsafe-inline'",
  'font-src data:',
  'img-src data:',
  "base-uri 'none'",
  "form-action 'none'",
].join('; ');

const page = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="${csp}">
<title>RAP pre-check</title>
<!-- RAP pre-check report, written by csv-generator-nextgen.py. Page built from csv-generator-ui/ with
${titles.join('\n')}
Open Sans font: SIL Open Font License 1.1. License texts at the end of this file. -->
<style>
${fonts.join('\n')}
${css}</style>
</head>
<body>
<noscript><p style="font-family: sans-serif; padding: 20px;">This report page needs JavaScript. Open the .xlsx copy of the report instead.</p></noscript>
<div id="root"></div>
<script type="application/json" id="rap-data">${PLACEHOLDER}</script>
<script>${js}</script>
</body>
</html>
<!--
${licenses}
-->
`;

mkdirSync('dist', { recursive: true });
writeFileSync('dist/report-page.html', page);
const sha256 = createHash('sha256').update(page, 'utf8').digest('hex');
console.log(`dist/report-page.html: ${page.length} characters, SHA-256 ${sha256}`);

const scriptPath = process.argv[2];
if (scriptPath) {
  const source = readFileSync(scriptPath, 'utf8');
  const start = source.indexOf(BEGIN);
  const end = source.indexOf(END);
  if (start < 0 || end < start) {
    throw new Error(`${scriptPath} has no "${BEGIN}" ... "${END}" block`);
  }
  const encoded = deflateSync(Buffer.from(page, 'utf8'), { level: 9 }).toString('base64').match(/.{1,100}/g).join('\n');
  const versions = ['react', '@cloudscape-design/components'].map(name => packages.get(name).title).join(', ');
  const block =
    `${BEGIN} (generated by csv-generator-ui/build.mjs, do not edit)\n` +
    `# ${versions}. SHA-256 of the page: ${sha256}\n` +
    `REPORT_PAGE = """\n${encoded}\n"""\n`;
  writeFileSync(scriptPath, source.slice(0, start) + block + source.slice(end));
  console.log(`${scriptPath}: page embedded, ${encoded.length} characters`);
}
